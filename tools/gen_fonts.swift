// Rasterizes TrueType fonts into 8-bit antialiased glyph tables for the firmware.
//
//   swift tools/gen_fonts.swift > src/fonts_data.h
//
// Fonts: Roboto / Roboto Condensed (Apache License 2.0, Google).
import Foundation
import CoreGraphics
import CoreText

struct FontSpec {
    let name: String      // C identifier
    let file: String      // TTF file in tools/fonts
    let px: CGFloat       // em size in pixels
    let chars: String     // glyph set
    let tracking: Int     // extra advance in px
    var slant: CGFloat = 0  // synthetic italic: degrees the glyphs lean right
}

let ascii = String((32...126).map { Character(UnicodeScalar($0)!) }) + "°"
let numeric = " 0123456789-+.°"

let specs: [FontSpec] = [
    FontSpec(name: "font_giant", file: "RobotoCondensed-Bold.ttf",    px: 116, chars: "0123456789-", tracking: 0),
    FontSpec(name: "font_huge",  file: "RobotoCondensed-Bold.ttf",    px: 92, chars: numeric, tracking: 0),
    FontSpec(name: "font_big",   file: "RobotoCondensed-Bold.ttf",    px: 50, chars: ascii,   tracking: 0),
    FontSpec(name: "font_med",   file: "Roboto-Medium.ttf",           px: 26, chars: ascii,   tracking: 0),
    FontSpec(name: "font_small", file: "Roboto-Bold.ttf",             px: 17, chars: ascii,   tracking: 1),
    FontSpec(name: "font_tiny",  file: "RobotoCondensed-Regular.ttf", px: 15, chars: ascii,   tracking: 0),
]

let scriptDir = URL(fileURLWithPath: CommandLine.arguments[0]).deletingLastPathComponent()
var out = """
// AUTO-GENERATED by tools/gen_fonts.swift — do not edit.
// Glyphs rendered from Roboto / Roboto Condensed (Apache License 2.0).
#pragma once
#include "fonts.h"

"""

for spec in specs {
    let url = scriptDir.appendingPathComponent("fonts").appendingPathComponent(spec.file)
    guard let provider = CGDataProvider(url: url as CFURL), let cgFont = CGFont(provider) else {
        FileHandle.standardError.write("cannot load \(url.path)\n".data(using: .utf8)!)
        exit(1)
    }
    var skew = CGAffineTransform(a: 1, b: 0, c: tan(spec.slant * .pi / 180), d: 1, tx: 0, ty: 0)
    let ctFont = CTFontCreateWithGraphicsFont(cgFont, spec.px, &skew, nil)
    let ascent = Int(CTFontGetAscent(ctFont).rounded())
    let descent = Int(CTFontGetDescent(ctFont).rounded())

    var codes = Array(Set(spec.chars.unicodeScalars.map { UInt16($0.value) })).sorted()
    codes = codes.filter { $0 >= 32 }

    var bitmap: [UInt8] = []
    var glyphRows: [String] = []

    for code in codes {
        var ch: UniChar = code
        var glyph: CGGlyph = 0
        CTFontGetGlyphsForCharacters(ctFont, &ch, &glyph, 1)
        var adv = CGSize.zero
        CTFontGetAdvancesForGlyphs(ctFont, .horizontal, &glyph, &adv, 1)
        var bbox = CGRect.zero
        CTFontGetBoundingRectsForGlyphs(ctFont, .horizontal, &glyph, &bbox, 1)

        let pad = 2 + Int((spec.px * tan(spec.slant * .pi / 180)).rounded(.up))
        let minX = Int(floor(bbox.minX)), minY = Int(floor(bbox.minY))
        let maxX = Int(ceil(bbox.maxX)), maxY = Int(ceil(bbox.maxY))
        let W = max(1, maxX - minX + 2 * pad)
        let H = max(1, maxY - minY + 2 * pad)
        let ox = pad - minX, oy = pad - minY   // baseline origin in context coords (y up)

        var buf = [UInt8](repeating: 0, count: W * H)
        buf.withUnsafeMutableBytes { raw in
            let ctx = CGContext(data: raw.baseAddress, width: W, height: H, bitsPerComponent: 8,
                                bytesPerRow: W, space: CGColorSpaceCreateDeviceGray(),
                                bitmapInfo: CGImageAlphaInfo.none.rawValue)!
            ctx.setShouldAntialias(true)
            ctx.setAllowsFontSmoothing(false)
            ctx.setShouldSubpixelPositionFonts(false)
            ctx.setFillColor(gray: 1, alpha: 1)
            var pos = CGPoint(x: CGFloat(ox), y: CGFloat(oy))
            CTFontDrawGlyphs(ctFont, &glyph, &pos, 1, ctx)
        }
        // Crop to inked area (row 0 of buf is the TOP of the image).
        var x0 = W, y0 = H, x1 = -1, y1 = -1
        for y in 0..<H { for x in 0..<W where buf[y * W + x] > 0 {
            x0 = min(x0, x); x1 = max(x1, x); y0 = min(y0, y); y1 = max(y1, y)
        } }
        let offset = bitmap.count
        var gw = 0, gh = 0, xoff = 0, yoff = 0
        if x1 >= 0 {
            gw = x1 - x0 + 1; gh = y1 - y0 + 1
            for y in y0...y1 { for x in x0...x1 { bitmap.append(buf[y * W + x]) } }
            xoff = x0 - ox                 // left of bitmap relative to pen x
            yoff = y0 - (H - oy)           // top of bitmap relative to baseline (y down)
        }
        let advance = Int(adv.width.rounded()) + spec.tracking
        glyphRows.append("  {\(offset), \(gw), \(gh), \(xoff), \(yoff), \(advance)}, // '\(code == 92 ? "\\\\" : String(UnicodeScalar(code)!))'")
    }

    out += "static const uint8_t \(spec.name)_bitmap[] = {\n"
    for i in stride(from: 0, to: bitmap.count, by: 32) {
        out += "  " + bitmap[i..<min(i + 32, bitmap.count)].map { String($0) }.joined(separator: ",") + ",\n"
    }
    out += "};\n"
    out += "static const uint16_t \(spec.name)_codes[] = {" + codes.map { String($0) }.joined(separator: ",") + "};\n"
    out += "static const Glyph \(spec.name)_glyphs[] = {\n" + glyphRows.joined(separator: "\n") + "\n};\n"
    out += "const Font \(spec.name) = {\(spec.name)_bitmap, \(spec.name)_glyphs, \(spec.name)_codes, \(codes.count), \(ascent), \(descent)};\n\n"
}

print(out)
