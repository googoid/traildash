// Generates src/logo_data.h from the boot-screen badge image (toyota-logo.png).
//   swift tools/gen_logo.swift [toyota-logo.png] [src/logo_data.h]
// The badge's rings and stripes are drawn as vectors in ui.cpp (geometry measured
// from the image, in image pixels relative to the badge centre). Only the white
// lettering is extracted here, as an 8-bit alpha mask cut into slices
// (glyph codes 'a'..), so it can be drawn with the normal text renderer.
import CoreGraphics; import ImageIO; import Foundation

let args = CommandLine.arguments
let inPath = args.count > 1 ? args[1] : "toyota-logo.png"
let outPath = args.count > 2 ? args[2] : "src/logo_data.h"
let CX = 281, CY = 271          // badge centre in the image
let R_IN = 182                  // inside the white ring
let BAND = 52                   // lettering lies within CY +- BAND (between the stripes)

let src = CGImageSourceCreateWithURL(URL(fileURLWithPath: inPath) as CFURL, nil)!
let img = CGImageSourceCreateImageAtIndex(src, 0, nil)!
let W = img.width, H = img.height
var buf = [UInt8](repeating: 0, count: W * H * 4)
let ctx = CGContext(data: &buf, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W * 4,
                    space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
ctx.draw(img, in: CGRect(x: 0, y: 0, width: W, height: H))

// alpha = whiteness of neutral pixels inside the inner circle, within the band
func alpha(_ x: Int, _ y: Int) -> UInt8 {
  let dx = x - CX, dy = y - CY
  if abs(dy) > BAND || dx * dx + dy * dy > R_IN * R_IN { return 0 }
  let i = (y * W + x) * 4
  let r = Int(buf[i]), g = Int(buf[i + 1]), b = Int(buf[i + 2])
  if max(r, g, b) - min(r, g, b) > 48 { return 0 }   // coloured stripe pixel
  let v = min(r, g, b)
  return v < 24 ? 0 : UInt8(min(255, (v - 24) * 255 / 231))
}

var left = W, right = 0, top = H, bot = 0
for y in 0..<H { for x in 0..<W where alpha(x, y) > 0 {
  left = min(left, x); right = max(right, x); top = min(top, y); bot = max(bot, y) } }
let h = bot - top + 1
// Glyph width is a uint8_t, so cut the lettering into equal slices of <= 255 px.
let total = right - left + 1
let n = (total + 254) / 255
var bytes: [UInt8] = []
var glyphs: [String] = []
var codes: [String] = []
for k in 0..<n {
  let a = left + total * k / n, b = left + total * (k + 1) / n - 1
  let w = b - a + 1
  glyphs.append("  {\(bytes.count), \(w), \(h), 0, \(top - CY), \(w)},")
  codes.append("'\(Character(UnicodeScalar(97 + k)!))'")
  for y in top...bot { for xx in a...b { bytes.append(alpha(xx, y)) } }
}
let text = (0..<n).map { String(Character(UnicodeScalar(97 + $0)!)) }.joined()

var out = "// AUTO-GENERATED by tools/gen_logo.swift from \((inPath as NSString).lastPathComponent) — do not edit.\n"
out += "#pragma once\n#include \"logo.h\"\n\n"
out += "// glyph yoff is relative to the badge centre; pen starts at LOGO_TEXT_X0 from the centre\n"
out += "static constexpr int LOGO_TEXT_X0_ = \(left - CX);\n"
out += "static const uint8_t logo_bitmap[] = {\n"
for i in stride(from: 0, to: bytes.count, by: 32) {
  out += "  " + bytes[i..<min(i + 32, bytes.count)].map { String($0) }.joined(separator: ",") + ",\n"
}
out += "};\nstatic const Glyph logo_glyphs[] = {\n" + glyphs.joined(separator: "\n") + "\n};\n"
out += "static const uint16_t logo_codes[] = {" + codes.joined(separator: ",") + "};\n"
out += "const Font font_logo = {logo_bitmap, logo_glyphs, logo_codes, \(n), \(CY - top), \(bot - CY)};\n"
out += "const int LOGO_TEXT_X0 = LOGO_TEXT_X0_;\nconst char* const LOGO_TEXT = \"\(text)\";\n"
try! out.write(toFile: outPath, atomically: true, encoding: .utf8)
print("cols \(left)...\(right)  rows \(top)...\(bot)  \(bytes.count) bytes")
